// Dev-only capture: title (new buttons), hangar, survival HUD + level-up cards, survival results.
import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright");
const url = process.argv[2] ?? "http://localhost:4173/";
const out = process.argv[3] ?? "./captures";
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 412, height: 915 }, deviceScaleFactor: 2, hasTouch: true, isMobile: true });
const errors = [];
page.on("console", (m) => { if (m.type() === "error" || m.type() === "warning") errors.push(`${m.type()}: ${m.text()}`); });
page.on("pageerror", (e) => errors.push(`pageerror: ${e.message}`));
await page.goto(url);
await page.waitForTimeout(700);
await page.evaluate(() => { const a = window.__rb; a.profile.credits = 900; a.profile.weapon_research.W011 = 1; a.save(); a.showTitle(); });
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/v01_title.png` });
await page.getByRole("button", { name: /โรงเก็บยาน|Hangar/ }).click();
await page.waitForTimeout(300);
await page.getByRole("button", { name: /^\s*180\s*$/ }).first().click({ timeout: 2000 }).catch(() => {});
await page.waitForTimeout(200);
await page.getByRole("button", { name: /กระเปาะจรวด|Seeker/ }).click({ timeout: 2000 }).catch(() => {});
await page.waitForTimeout(300);
await page.screenshot({ path: `${out}/v02_hangar.png` });
await page.getByRole("button", { name: /^กลับ$|^Back$/ }).click();
await page.waitForTimeout(200);
await page.getByRole("button", { name: /เอาตัวรอด|Survival/ }).click();
await page.waitForTimeout(400);
await page.evaluate(() => { const w = window.__rb.screen.world; w.opts.invulnerable = true;
  for (let i = 0; i < 60 * 60 && !w.levelUp; i++) { const t = w.enemies.find((e) => e.pos.y > 80 && e.pos.y < 800 && e.pos.x > 40 && e.pos.x < 680); w.step({ move: t ? { x: Math.sign(t.pos.x - w.motion.pos.x) * 0.7, y: 0 } : { x: 0, y: 0 }, fire: true }); } });
await page.waitForTimeout(500);
await page.screenshot({ path: `${out}/v03_levelup.png` });
await page.locator(".pick").first().click();
await page.waitForTimeout(600);
await page.screenshot({ path: `${out}/v04_hud.png` });
await page.evaluate(() => { const w = window.__rb.screen.world; w.opts.invulnerable = false; w.hp = 0; w.step({ move: { x: 0, y: 0 }, fire: false }); });
await page.waitForTimeout(2200);
await page.screenshot({ path: `${out}/v05_results.png` });
console.log(errors.length ? errors.join("\n") : "no console errors");
await browser.close();
