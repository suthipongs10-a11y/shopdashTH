/* --------------------------------------------------------------- helpers */

export function getService(slug: string): Service | undefined {
  return services.find((s) => s.slug === slug);
}

export function getProvince(slug: string): Province | undefined {
  return provinces.find((p) => p.slug === slug);
}

export function getDistrict(provinceSlug: string, districtSlug: string): District | undefined {
  return getProvince(provinceSlug)?.districts.find((d) => d.slug === districtSlug);
}

/** ชื่อสั้นไว้เขียนในประโยค เช่น "ช่างในพื้นที่วารินฯ" */
export function districtShort(d: District): string {
  return d.shortTh ?? d.nameTh;
}

export function servicePath(serviceSlug: string): string {
  return `/${serviceSlug}/`;
}

export function provincePath(serviceSlug: string, provinceSlug: string): string {
  return `/${serviceSlug}/${provinceSlug}/`;
}

export function districtPath(
  serviceSlug: string,
  provinceSlug: string,
  districtSlug: string,
): string {
  return `/${serviceSlug}/${provinceSlug}/${districtSlug}/`;
}

/** จำนวนอำเภอที่ให้บริการทั้งหมด ใช้โชว์บนหน้าแรก */
export function totalDistricts(): number {
  return provinces.reduce((sum, p) => sum + p.districts.length, 0);
}
